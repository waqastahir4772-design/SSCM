$error = '';

if ($_SERVER['REQUEST_METHOD'] == 'POST' && isset($_POST['login'])) {
    $username = escape($_POST['username']);
    $password = $_POST['password']; // In demo, we compare directly. In production use password_verify()

    if (empty($username) || empty($password)) {
        $error = "Please enter both username and password.";
    } else {
        $sql = "SELECT * FROM users WHERE username = '$username' AND status = 'Active' LIMIT 1";
        $result = $conn->query($sql);

        if ($result->num_rows == 1) {
            $user = $result->fetch_assoc();
            // Demostration check (plain text)
            if ($password === $user['password']) {
                $_SESSION['user_id'] = $user['id'];
                $_SESSION['username'] = $user['username'];
                $_SESSION['full_name'] = $user['full_name'];
                $_SESSION['role'] = $user['role'];
                $_SESSION['department_id'] = $user['department_id'];

                redirect('dashboard.php');
            } else {
                $error = "Invalid password.";
            }
        } else {
            $error = "User not found or account inactive.";
        }
    }
}
